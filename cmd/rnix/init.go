// Story 48.4 — `rnix init --with-mcp-examples`.
//
// Test-injection seam: redirect config.GlobalDir() to a tempdir.
// ATDD swaps globalDirForInit just like check.go's mcpConfigPathForCheck.
var globalDirForInit string

// mcpExampleYAML is the byte-stable template emitted by
// `rnix init --with-mcp-examples`. Must be ASCII-only and free of timestamps
// or per-machine tokens so tests can byte-equal compare (Story §AC1 + 易错点 11).
const mcpExampleYAML = `# rnix MCP servers configuration
# Generated by ` + "`rnix init --with-mcp-examples`" + `.
#
# This file declares MCP (Model Context Protocol) servers that rnix agents
# can mount via their agent.yaml's ` + "`mcp:`" + ` field. Each server is launched
# as a subprocess and communicates over stdio.
#
# Quick verification:
#   rnix check mcp                  # Check node/npx/Chromium prerequisites
#   rnix mcp test playwright        # One-shot connectivity probe
#   rnix --agent playwright-demo --intent "open https://example.com and screenshot"
#
# Reference: https://modelcontextprotocol.io/

servers:
  # Playwright MCP — official browser automation server.
  # Prerequisites: node >= 18, npx (ships with npm), Chromium browser.
  # Install Chromium once: ` + "`npx playwright install chromium`" + `
  playwright:
    command: npx
    args:
      - "-y"
      - "@playwright/mcp@latest"
    transport_type: stdio
    instructions: |
      Use this server for browser automation: navigate to URLs,
      take screenshots, click elements, fill forms. Tools appear in
      the agent's tool list as native functions named
      mcp__playwright__<tool> (e.g. mcp__playwright__browser_navigate).

  # Add additional servers below. Examples:
  #
  # filesystem:
  #   command: npx
  #   args: ["-y", "@modelcontextprotocol/server-filesystem", "/tmp"]
  #   transport_type: stdio
  #
  # github:
  #   command: npx
  #   args: ["-y", "@modelcontextprotocol/server-github"]
  #   transport_type: stdio
  #   env:
  #     # NOTE: rnix does not expand ${VAR} placeholders. Replace this with
  #     # the actual token value before use, or wire your secret manager to
  #     # rewrite this file at provisioning time.
  #     GITHUB_TOKEN: "${GITHUB_TOKEN}"
`

var initCmd = &cobra.Command{
	Use:   "init",
	Short: "Initialize Rnix configuration environment",
	Long:  "Initialize global configuration (~/.config/rnix/) and project configuration (.rnix/) directories.",
	RunE:  runInit,
}

func init() {
	initCmd.Flags().Bool("with-mcp-examples", false, "Generate mcp.yaml with Playwright MCP example server")
}

func runInit(cmd *cobra.Command, args []string) error {
	w := cmd.OutOrStdout()

	// Global initialization
	globalDir := globalDirForInit
	if globalDir == "" {
		resolved, err := config.GlobalDir()
		if err != nil {
			return fmt.Errorf("resolve global config directory: %w", err)
		}
		globalDir = resolved
	}

	if globalNeedsInit(globalDir) {
		if err := initGlobal(globalDir); err != nil {
			return fmt.Errorf("global init failed: %w", err)
		}
		fmt.Fprintf(w, "initialized global config: %s\n", globalDir)
	} else {
		fmt.Fprintln(w, "global config already exists, skipping")
	}

	// Project initialization (skipped when globalDirForInit is set — test mode)
	if globalDirForInit == "" {
		cwd, err := os.Getwd()
		if err != nil {
			return fmt.Errorf("get working directory: %w", err)
		}
		rnixDir := filepath.Join(cwd, ".rnix")
		info, err := os.Stat(rnixDir)
		switch {
		case os.IsNotExist(err):
			if err := initProject(cwd); err != nil {
				return fmt.Errorf("project init failed: %w", err)
			}
			fmt.Fprintf(w, "initialized project config: %s\n", rnixDir)
		case err == nil && !info.IsDir():
			return fmt.Errorf(".rnix exists as a file, not a directory — please remove it first: %s", rnixDir)
		default:
			fmt.Fprintln(w, "project already initialized, skipping")
		}
	}

	// Story 48.4 — optional MCP example scaffold.
	withMcp := resolveInitWithMcpFlag(cmd)
	if withMcp {
		// In test mode, --quiet may have been passed via initCmd.SetArgs but
		// not propagated to rootCmd's PersistentFlag binding. Fall back to
		// scanning the raw args slice so quiet behaviour stays consistent.
		quiet := flagQuiet
		if !quiet {
			for _, a := range readCommandArgs(cmd) {
				if a == "--quiet" || a == "-q" {
					quiet = true
					break
				}
			}
		}
		mcpPath := filepath.Join(globalDir, "mcp.yaml")
		wrote, err := writeMcpYamlExample(globalDir)
		if err != nil {
			return fmt.Errorf("write mcp.yaml: %w", err)
		}
		if wrote {
			fmt.Fprintf(w, "wrote mcp.yaml: %s\n", mcpPath)
		} else {
			fmt.Fprintf(w, "mcp.yaml already exists, skipping (path: %s)\n", mcpPath)
		}
		renderInitMcpGuidance(w, mcpPath, quiet)
	}

	return nil
}

// globalNeedsInit returns true when the global config directory is missing or
// lacks key artifacts (providers.yaml, agents/). The directory itself may exist
// (e.g. recreated by ui-state.json writes) while the actual config is absent.
func globalNeedsInit(globalDir string) bool {
	for _, sub := range []string{
		"providers.yaml",
		"agents",
	} {
		if _, err := os.Stat(filepath.Join(globalDir, sub)); os.IsNotExist(err) {
			return true
		}
	}
	return false
}

func initGlobal(globalDir string) error {
	// Create directory structure
	if err := os.MkdirAll(globalDir, 0o755); err != nil {
		return err
	}
	agentsDir := filepath.Join(globalDir, "agents")
	if err := os.MkdirAll(agentsDir, 0o755); err != nil {
		return err
	}
	skillsDir := filepath.Join(globalDir, "skills")
	if err := os.MkdirAll(skillsDir, 0o755); err != nil {
		return err
	}

	// Extract embedded agents and skills
	if err := config.ExtractEmbedded(rnix.EmbeddedAgents, "lib/agents", agentsDir); err != nil {
		return fmt.Errorf("extract agents: %w", err)
	}
	if err := config.ExtractEmbedded(rnix.EmbeddedSkills, "lib/skills", skillsDir); err != nil {
		return fmt.Errorf("extract skills: %w", err)
	}

	// Generate default providers.yaml
	if err := writeDefaultProviders(globalDir); err != nil {
		return fmt.Errorf("write providers.yaml: %w", err)
	}

	// Generate default config.yaml
	if err := writeDefaultConfig(globalDir); err != nil {
		return fmt.Errorf("write config.yaml: %w", err)
	}

	// Generate global init.yaml template. The daemon reads its bootstrap config
	// (services + supervisor trees) ONLY from <globalDir>/init.yaml — it is a
	// single shared per-user process, so bootstrap is a global concern (never
	// project-scoped). Defaults to an empty service list so the daemon starts
	// cleanly; mcp_manager is loaded implicitly regardless.
	initPath := filepath.Join(globalDir, "init.yaml")
	if _, err := os.Stat(initPath); os.IsNotExist(err) {
		if err := os.WriteFile(initPath, []byte(globalInitYAMLTemplate), 0o644); err != nil {
			return fmt.Errorf("write init.yaml: %w", err)
		}
	}

	return nil
}

// globalInitYAMLTemplate is the scaffold written to <globalDir>/init.yaml by
// `rnix init`. It documents the supported schema and defaults to an empty
// service list so the daemon starts cleanly.
const globalInitYAMLTemplate = `# rnix daemon init configuration (~/.config/rnix/init.yaml)
#
# Read by the shared per-user daemon at startup. Bootstrap is GLOBAL: the daemon
# is a single process across all projects, so it does NOT read any project-level
# .rnix/init.yaml. Two sections are supported:
#
# services:    init-time setup, each item is a ServiceConfig
#   - name:     display name
#     type:     registered service type (skill_registry | mcp_manager | log_aggregator)
#     required: true -> bootstrap aborts on failure; false -> warn and continue
#     config:   type-specific key/value map
#
# supervisors: long-running supervised agent trees, each item is a
#   SupervisorConfig with a children: list of {name, agent, intent, model, ...}.
#
# Note: mcp_manager is loaded automatically even when omitted, so MCP servers
# declared in mcp.yaml are always resolvable by ` + "`rnix mcp test/list`" + `.

services: []
`

func initProject(projectDir string) error {
	// Create directory structure
	for _, sub := range []string{".rnix/agents", ".rnix/skills", ".rnix/data", ".rnix/state"} {
		if err := os.MkdirAll(filepath.Join(projectDir, sub), 0o755); err != nil {
			return err
		}
	}

	// Generate project config.yaml (only comments)
	configPath := filepath.Join(projectDir, ".rnix", "config.yaml")
	if _, err := os.Stat(configPath); os.IsNotExist(err) {
		content := "# Rnix project configuration\n# See documentation for available options\n"
		if err := os.WriteFile(configPath, []byte(content), 0o644); err != nil {
			return err
		}
	}

	return nil
}

