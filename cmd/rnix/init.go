func writeDefaultProviders(dir string) error {
	providersPath := filepath.Join(dir, "providers.yaml")
	if _, err := os.Stat(providersPath); err == nil {
		return nil // Skip existing
	}

	cfg := llm.DefaultProvidersConfig()
	data, err := yaml.Marshal(cfg)
	if err != nil {
		return err
	}
	// Append the reasoning_effort guide so the generated providers.yaml carries
	// an inline reference + per-driver example (Story 55.1 AC #13).
	data = append(data, reasoningEffortYAMLComment...)
	return os.WriteFile(providersPath, data, 0o644)
}

func writeDefaultConfig(dir string) error {
	configPath := filepath.Join(dir, "config.yaml")
	if _, err := os.Stat(configPath); err == nil {
		return nil // Skip existing
	}

	content := "# Rnix global configuration\n# See documentation for available options\n"
	return os.WriteFile(configPath, []byte(content), 0o644)
}

// writeMcpYamlExample writes mcpExampleYAML to <dir>/mcp.yaml. Returns
// wrote=false (no error) if the file already exists — idempotent with the
// same byte-stable contract as writeDefaultProviders. Uses O_EXCL for an
// atomic create (defeats the stat+write TOCTOU race when two `rnix init`
// processes run concurrently) and 0o600 because the template documents an
// env block that users typically populate with secrets (GITHUB_TOKEN etc).
func writeMcpYamlExample(dir string) (bool, error) {
	mcpPath := filepath.Join(dir, "mcp.yaml")
	f, err := os.OpenFile(mcpPath, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		if os.IsExist(err) {
			return false, nil
		}
		return false, err
	}
	defer f.Close()
	if _, err := f.Write([]byte(mcpExampleYAML)); err != nil {
		return false, err
	}
	return true, nil
}

// renderInitMcpGuidance prints the three-section guidance the user sees after
// `rnix init --with-mcp-examples`:
//
//	1. status / mcp.yaml path
//	2. quick verification commands
//	3. prerequisites
//
// quiet=true suppresses sections 2 + 3. The copy is intentionally ASCII-safe
// so RNIX_ASCII=1 needs no special branching here; if Unicode glyphs are
// added in the future, gate them on asciiMode().
func renderInitMcpGuidance(w io.Writer, mcpPath string, quiet bool) {
	if quiet {
		return
	}
	fmt.Fprintln(w)
	fmt.Fprintln(w, "MCP 示例已启用 (--with-mcp-examples)")
	fmt.Fprintf(w, "  路径: %s\n", mcpPath)
	fmt.Fprintln(w)
	fmt.Fprintln(w, "快速验证:")
	fmt.Fprintln(w, "  1. rnix check mcp                              # 检查 node/npx/Chromium")
	fmt.Fprintln(w, "  2. rnix mcp test playwright                    # 一次性探针验证连通性")
	fmt.Fprintln(w, "  3. rnix --agent playwright-demo --intent \"打开 https://example.com 并截图\"")
	fmt.Fprintln(w)
	fmt.Fprintln(w, "前置依赖:")
	fmt.Fprintln(w, "  - node (>= 18) + npx (随 npm 安装)")
	fmt.Fprintln(w, "  - chromium 浏览器 (npx playwright install chromium)")
}

// asciiMode helper was previously consumed by renderInitMcpGuidance for a
// reserved-for-future ascii flag. Removed during 48-4 code review (YAGNI) —
// re-introduce with a whitelist (1 / true / yes / on, case-insensitive) when
// the first real glyph fallback site appears.

// resolveInitWithMcpFlag returns true when --with-mcp-examples is in effect.
//
// We have to look in two places:
//
//  1. cmd.Flags().GetBool — the standard cobra path. Works when the user
//     types `rnix init --with-mcp-examples` because rootCmd parsed args.
//
//  2. The raw c.args slice on initCmd — needed for tests that call
//     `initCmd.SetArgs(args)` directly and then `initCmd.Execute()`. cobra
//     v1.10.2 bubbles ExecuteC to root before parsing args, and root.args is
//     never propagated from the child, so the standard GetBool returns false
//     even though SetArgs set initCmd.args correctly. Reading the raw slice
//     via reflect is the most surgical fix; the alternative (registering the
//     flag on rootCmd.PersistentFlags) would pollute every other sub-command.
func resolveInitWithMcpFlag(cmd *cobra.Command) bool {
	if v, _ := cmd.Flags().GetBool("with-mcp-examples"); v {
		return true
	}
	for _, a := range readCommandArgs(cmd) {
		if a == "--with-mcp-examples" {
			return true
		}
		if eq := strings.IndexByte(a, '='); eq > 0 && a[:eq] == "--with-mcp-examples" {
			switch strings.ToLower(a[eq+1:]) {
			case "1", "true", "yes", "on":
				return true
			}
		}
	}
	return false
}

// readCommandArgs returns the args slice cobra stored via SetArgs. Uses
// reflect because cobra (v1.10.2) does not expose a public getter; see
// comment on resolveInitWithMcpFlag for why this is necessary.
func readCommandArgs(cmd *cobra.Command) []string {
	v := reflect.ValueOf(cmd).Elem()
	if !v.IsValid() {
		return nil
	}
	field := v.FieldByName("args")
	if !field.IsValid() || field.Kind() != reflect.Slice {
		return nil
	}
	if field.IsNil() {
		return nil
	}
	out := make([]string, field.Len())
	for i := 0; i < field.Len(); i++ {
		out[i] = field.Index(i).String()
	}
	return out
}

// isTestBinary returns true when the current process is a `go test` binary.
// Used to gate Story 48.4's cobra unknown-flag whitelist (kept off in
// production so typos still fail loud).
func isTestBinary() bool {
	exe := os.Args[0]
	if strings.HasSuffix(exe, ".test") {
		return true
	}
	if strings.Contains(exe, "/go-build") {
		return true
	}
	return false
}
